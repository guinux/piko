//! The `key = value` line grammar of a package's `.PKGINFO`.
//!
//! This is libalpm's reader (`be_package.c:parse_descfile`). Each line is a key, the three
//! characters ` = `, and a value that runs to the end of the line. A line that is empty, or
//! holds only white space, is skipped. A line that starts with `#` is a comment. A key may
//! appear on several lines: a list key, such as `depend`, adds one value per line.
//!
//! libalpm logs a line without ` = ` and skips it. [`Pairs`] reports it instead, through
//! [`Pairs::first_malformed_line`]: the caller reads a list that decides an install, and a
//! line it cannot read may hide an entry of that list.
//!
//! The reader builds nothing. Every [`Pair`] borrows the text it came from.

use std::str::Lines;

/// One `key = value` line, borrowed from the text.
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
#[non_exhaustive]
pub struct Pair<'a> {
    /// The key, before the first space.
    pub key: &'a str,
    /// The value, after ` = `, possibly empty.
    pub value: &'a str,
    /// The 1-based line number.
    pub line: usize,
}

/// Every `key = value` line of a text, in order.
#[derive(Debug)]
pub struct Pairs<'a> {
    lines: Lines<'a>,
    /// The number of lines already read.
    read: usize,
    /// The 1-based number of the first line that is not a pair, a comment or empty.
    first_malformed: Option<usize>,
}

impl<'a> Pairs<'a> {
    /// Reads the pairs of `text`.
    #[must_use]
    pub fn new(text: &'a str) -> Self {
        Self { lines: text.lines(), read: 0, first_malformed: None }
    }

    /// The first line read so far that is not a pair, a comment or empty.
    #[must_use]
    pub const fn first_malformed_line(&self) -> Option<usize> {
        self.first_malformed
    }
}

impl<'a> Iterator for Pairs<'a> {
    type Item = Pair<'a>;

    fn next(&mut self) -> Option<Pair<'a>> {
        loop {
            let line = self.lines.next()?;
            // The line count is bounded by the text length, so this cannot overflow.
            self.read = self.read.saturating_add(1);
            if line.trim().is_empty() || line.starts_with('#') {
                continue;
            }
            // The key ends at the first space, which must open the ` = ` delimiter.
            let parsed = line
                .split_once(' ')
                .and_then(|(key, rest)| Some((key, rest.strip_prefix("= ")?)))
                .filter(|(key, _)| !key.is_empty() && !key.contains('='));
            match parsed {
                Some((key, value)) => return Some(Pair { key, value, line: self.read }),
                None => {
                    if self.first_malformed.is_none() {
                        self.first_malformed = Some(self.read);
                    }
                }
            }
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    fn read(text: &str) -> (Vec<(&str, &str)>, Option<usize>) {
        let mut pairs = Pairs::new(text);
        let found = pairs.by_ref().map(|pair| (pair.key, pair.value)).collect();
        (found, pairs.first_malformed_line())
    }

    #[test]
    fn reads_pairs_in_order() {
        let text = "pkgname = foo\npkgver = 1.0-1\ndepend = bar\ndepend = baz>=2\n";
        assert_eq!(
            read(text),
            (
                vec![
                    ("pkgname", "foo"),
                    ("pkgver", "1.0-1"),
                    ("depend", "bar"),
                    ("depend", "baz>=2")
                ],
                None
            )
        );
    }

    #[test]
    fn skips_comments_and_empty_lines() {
        let text = "# Generated by makepkg\n\npkgname = foo\n   \n# using fakeroot\n";
        assert_eq!(read(text), (vec![("pkgname", "foo")], None));
    }

    /// The value runs to the end of the line, spaces and ` = ` included.
    #[test]
    fn the_value_is_the_rest_of_the_line() {
        let text = "pkgdesc = a = b  \noptdepend = foo: for the = sign\nurl = \n";
        assert_eq!(
            read(text).0,
            [("pkgdesc", "a = b  "), ("optdepend", "foo: for the = sign"), ("url", "")]
        );
    }

    #[test]
    fn reports_a_line_that_is_not_a_pair() {
        for text in ["pkgname=foo\n", "pkgname foo\n", "pkgname  = foo\n", " = foo\n", "a=b = c\n"]
        {
            let (pairs, malformed) = read(text);
            assert!(pairs.is_empty(), "{text:?}");
            assert_eq!(malformed, Some(1), "{text:?}");
        }
        let (pairs, malformed) = read("pkgname = foo\nbroken\nnext = 1\nalso broken\n");
        assert_eq!(pairs, [("pkgname", "foo"), ("next", "1")]);
        assert_eq!(malformed, Some(2), "the first malformed line is reported");
    }
}
